const assert = require('node:assert/strict');
require('ts-node/register/transpile-only');
const { approvalCycle, changeRelatedSql, projectParticipantSql } = require('../src/modules/tasks/approval-records.ts');
const log = (id, fromStatus, toStatus, operatorId = 1) => ({ id, taskId: 8, action: 'transition', fromStatus, toStatus, operatorId, payload: null, createdAt: new Date(2026, 9, 26, 10, id) });
const logs = [log(1,'doing','pending_accept'),log(2,'pending_accept','doing',2),log(3,'doing','pending_accept'),log(4,'pending_accept','done',3),log(5,'done','doing')];
assert.equal(approvalCycle(logs,1).status,'rejected');
assert.equal(approvalCycle(logs,1).decision.operatorId,2);
assert.equal(approvalCycle(logs,3).status,'approved');
assert.equal(approvalCycle(logs,4).submitted.id,3);
assert.equal(approvalCycle(logs,5),null);
assert.equal(approvalCycle([log(1,'doing','pending_accept')],1).status,'pending');
const confirm = [{...log(1,null,null),action:'create',payload:{status:'pending_confirm'}},log(2,'pending_confirm','todo',2)];
assert.equal(approvalCycle(confirm,1).status,'approved');
assert.equal(approvalCycle(confirm,2).kind,'confirm');
assert.equal(approvalCycle([log(2,'pending_accept','done')],2).submitted,null);
assert.equal(approvalCycle([log(2,'pending_accept','done')],2).status,'approved');
assert.equal(approvalCycle([log(1,'doing','pending_accept'),log(3,'doing','pending_accept')],1).status,'unknown');
assert.equal(approvalCycle([log(1,'doing','pending_accept'),log(2,'pending_accept','cancelled')],1).status,'cancelled');
assert.ok(changeRelatedSql.includes("ci.before->'assigneeIds'"));
assert.ok(!changeRelatedSql.includes("status != 'cancelled'"));
assert.ok(projectParticipantSql.includes('project_owners'));
console.log('Approval cycle tests passed (rejection, resubmission, later reopen, confirmation, missing history, cancellation).');
