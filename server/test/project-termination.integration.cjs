// Uses only a temporary schema on local PostgreSQL; notifications are stubbed.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { DataSource } = require('typeorm');
const { ProjectTerminationService } = require('../src/modules/tasks/project-termination.service');
const { TasksService } = require('../src/modules/tasks/tasks.service');
const entities = require('../src/entities');
const env = require('dotenv').parse(fs.readFileSync('.env'));
if (!['localhost', '127.0.0.1', '::1'].includes(env.DB_HOST || 'localhost')) throw Error('Local database only');
const options = { type: 'postgres', host: env.DB_HOST || 'localhost', port: Number(env.DB_PORT || 5432), username: env.DB_USERNAME, password: env.DB_PASSWORD, database: env.DB_DATABASE };
const schema = `termination_it_${process.pid}`;
const control = new DataSource(options);
let db;
const actor = (id, extra = {}) => ({ userId: id, name: `User ${id}`, roles: ['member'], managedDeptIds: [], deptId: 2, ...extra });
async function main() {
  await control.initialize();
  await control.query(`CREATE SCHEMA "${schema}"`);
  db = new DataSource({ ...options, schema, entities: entities.AllEntities, extra: { options: `-c search_path=${schema}` }, migrations: [path.resolve('src/migrations/*.ts')] });
  await db.initialize(); await db.runMigrations();
  process.env.FEISHU_BUSINESS_ROOT_DEPT = 'biz';
  delete process.env.PLAN_FINAL_APPROVER_USER_ID;
  await db.query(`INSERT INTO departments(id,name,feishu_dept_id,parent_feishu_id,head_user_id) VALUES (1,'示例业务公司','biz',null,null),(2,'研发','dev','biz',2),(3,'管理办公室','gm','biz',3),(4,'外部管理办公室','outside',null,4)`);
  await db.query(`INSERT INTO users(id,name,feishu_user_id,dept_id) VALUES (1,'负责人','one',2),(2,'部门负责人','two',2),(3,'管理办公室','three',3),(4,'外部','four',4)`);
  const notices = [];
  const service = new ProjectTerminationService(db, { sendCard: async (...args) => { notices.push(args); } });
  const tasks = Object.create(TasksService.prototype);
  for (const [field, entity] of Object.entries({ tasks: 'Task', projects: 'Project', projectOwners: 'ProjectOwner', planChanges: 'PlanChange', planChangeItems: 'PlanChangeItem', assignees: 'TaskAssignee', users: 'User', logs: 'TaskLog' })) tasks[field] = db.getRepository(entities[entity]);
  const assertInbox = async (expected) => {
    const inbox = await tasks.myTodoOverview(actor(1, { roles: ['admin'] }));
    assert.equal(inbox.todo.flatMap(g => g.tasks).length, expected, 'execution inbox follows project lifecycle');
    assert.equal(inbox.accept.flatMap(g => g.tasks).length, expected, 'acceptance inbox follows project lifecycle');
    assert.equal(inbox.confirm.flatMap(g => g.tasks).length, expected, 'confirmation inbox follows project lifecycle');
    assert.equal(inbox.ownedProjects.some(row => Number(row.id) === p), !!expected, 'managed inbox follows project lifecycle');
  };
  const create = async () => Number((await db.query(`INSERT INTO projects(name,dept_id,owner_id,created_by) VALUES ('终止测试',2,1,1) RETURNING id`))[0].id);
  const p = await create();
  await db.query('INSERT INTO project_owners(project_id,user_id) VALUES($1,1)', [p]);
  await db.query(`INSERT INTO tasks(project_id,title,creator_id,status,assignee_id,acceptor_id) VALUES ($1,'执行',1,'doing',1,1),($1,'验收',1,'pending_accept',1,1),($1,'确认',1,'pending_confirm',1,1)`, [p]);
  const [acceptance] = await db.query(`INSERT INTO task_logs(task_id,project_id,operator_id,action,from_status,to_status)
    SELECT id,project_id,1,'transition','doing','pending_accept' FROM tasks WHERE project_id=$1 AND title='验收' RETURNING id,task_id`,[p]);
  await assertInbox(1);
  await assert.rejects(service.request(actor(4), p, { reason: '越权' }), { status: 403 });
  const adminRequest = await service.request(actor(4, { roles: ['admin'] }), p, { reason: '管理员申请' });
  assert.equal(adminRequest.requesterId, 4);
  await service.withdraw(actor(4, { roles: ['admin'] }), adminRequest.id);
  notices.length = 0;
  await assert.rejects(service.request(actor(1, { readOnly: true }), p, { reason: '只读' }), { status: 403 });
  await assert.rejects(service.request(actor(1), p, { reason: ' ' }), { status: 400 });
  process.env.PLAN_FINAL_APPROVER_USER_ID = '4';
  await assert.rejects(service.request(actor(1), p, { reason: '配置越界' }), { status: 400 });
  delete process.env.PLAN_FINAL_APPROVER_USER_ID;
  const lock = db.createQueryRunner(); await lock.connect();
  await lock.query('SELECT pg_advisory_lock(21017,hashtext($1))', [String(p)]);
  try { await assert.rejects(service.request(actor(1), p, { reason: '锁竞争' }), { status: 409 }); }
  finally { await lock.query('SELECT pg_advisory_unlock(21017,hashtext($1))', [String(p)]); await lock.release(); }
  let r = await service.request(actor(1), p, { reason: '业务调整' });
  await assertInbox(0);
  assert.throws(() => tasks.assertProjectNotClosed({ terminationState: 'pending', status: 'active' }), { status: 400 });
  assert.equal(r.stage, 'department'); assert.equal(notices[0][1], 2);
  await assert.rejects(service.review(actor(2, { readOnly: true }), r.id, { approve: true }), { status: 403 });
  await assert.rejects(service.review(actor(2), r.id, { approve: 'true' }), { status: 400 });
  await assert.rejects(service.request(actor(1), p, { reason: '重复' }), { status: 400 });
  await assert.rejects(service.review(actor(3), r.id, { approve: true }), { status: 403 });
  await assert.rejects(service.withdraw(actor(2), r.id), { status: 403 });
  await service.withdraw(actor(1), r.id);
  await assertInbox(1);
  await assert.rejects(tasks.deleteProject(actor(1, { roles: ['admin'] }), p), { status: 400 });
  assert.equal((await db.query('SELECT count(*)::int n FROM tasks WHERE project_id=$1', [p]))[0].n, 3, 'history protection rejects before deleting tasks');
  assert.equal((await db.query('SELECT termination_state FROM projects WHERE id=$1', [p]))[0].termination_state, 'none');
  r = await service.request(actor(1), p, { reason: '再申请' });
  await service.review(actor(2), r.id, { approve: false, comment: '资料不齐' });
  await assertInbox(1);
  assert.equal((await db.query('SELECT termination_state FROM projects WHERE id=$1', [p]))[0].termination_state, 'none');
  r = await service.request(actor(1), p, { reason: '确认终止' });
  await db.query(`INSERT INTO tasks(project_id,title,creator_id,status) VALUES($1,'保留事实',1,'pending_accept')`, [p]);
  await db.query(`INSERT INTO plan_changes(project_id,reason,requester_id) VALUES($1,'待审批',1)`, [p]);
  await db.query(`INSERT INTO notifications(type,project_id,task_id,content,response) SELECT 'task_submitted_acceptance',$1,id,'待验收','{"message_id":"preserved"}' FROM tasks WHERE project_id=$1 AND title='保留事实'`, [p]);
  const [oldPlan] = await db.query(`INSERT INTO plan_changes(project_id,reason,requester_id,status) VALUES($1,'历史已通过',1,'approved') RETURNING id`,[p]);
  await db.query(`INSERT INTO notifications(type,project_id,plan_change_id,content,response) VALUES('plan_change_submitted',$1,$2,'历史已通过','{"reviewCard":{"original":true}}')`,[p,oldPlan.id]);
  await service.review(actor(2), r.id, { approve: true });
  const results = await Promise.allSettled([service.review(actor(3), r.id, { approve: true }), service.review(actor(3), r.id, { approve: true })]);
  assert.equal(results.filter(x => x.status === 'fulfilled').length, 1);
  assert.equal((await db.query('SELECT status FROM projects WHERE id=$1', [p]))[0].status, 'terminated');
  await assertInbox(0);
  assert.throws(() => tasks.assertProjectNotClosed({ terminationState: 'terminated', status: 'terminated' }), { status: 400 });
  const records = await tasks.approvalRecords(actor(1),'mine');
  assert.equal(records.find(row => row.kind==='accept' && Number(row.projectId)===p).status,'cancelled');
  const detail = await tasks.taskApprovalDetail(actor(1),Number(acceptance.task_id),Number(acceptance.id));
  assert.equal(detail.status,'cancelled'); assert.equal(detail.canReview,false);
  assert.equal(detail.currentTaskStatus,'pending_accept');
  assert.equal((await db.query("SELECT status FROM tasks WHERE project_id=$1 AND title='保留事实'", [p]))[0].status, 'pending_accept');
  assert.equal((await db.query('SELECT status FROM plan_changes WHERE project_id=$1', [p]))[0].status, 'cancelled');
  const notification = (await db.query('SELECT response FROM notifications WHERE project_id=$1', [p]))[0].response;
  assert.equal(notification.reviewClosed, true); assert.equal(notification.message_id, 'preserved');
  const oldNotice = (await db.query('SELECT response FROM notifications WHERE plan_change_id=$1',[oldPlan.id]))[0].response;
  assert.equal(oldNotice.reviewClosedReason, undefined); assert.equal(oldNotice.reviewCard.original,true);
  await assert.rejects(service.request(actor(1), p, { reason: '恢复' }), { status: 400 });
  const history = await service.list(actor(4, { readOnly: true }), p);
  assert.equal(history.length, 4); assert.equal(history[0].history.length, 3); assert.equal(history[0].canReview, false);
  // Same department/final approver reviews once, and requester never self-approves.
  await db.query('UPDATE departments SET head_user_id=3 WHERE id=2');
  const dedup = await service.request(actor(1), await create(), { reason: '去重' });
  assert.equal(dedup.stage, 'final');
  await service.review(actor(3), dedup.id, { approve: true });
  await db.query('UPDATE departments SET head_user_id=1 WHERE id=2');
  const ownHead = await service.request(actor(1), await create(), { reason: '本人部门负责人' });
  assert.equal(ownHead.stage, 'final');
  const anotherOwner = await create();
  await db.query('INSERT INTO project_owners(project_id,user_id) VALUES($1,2)', [anotherOwner]);
  const otherRequest = await service.request(actor(2), anotherOwner, { reason: '共同负责人申请' });
  assert.equal(otherRequest.requesterId, 2);
  process.env.PLAN_FINAL_APPROVER_USER_ID = '1';
  await assert.rejects(service.request(actor(1), await create(), { reason: '本人终审' }), { status: 400 });
  console.log('Project termination integration checks passed');
}
main().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => {
  if (db?.isInitialized) await db.destroy();
  if (control.isInitialized) { await control.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); await control.destroy(); }
});
